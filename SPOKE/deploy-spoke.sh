#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SCRIPT_DIR}/.env"
TIMESTAMP="$(date +%Y%m%d-%H%M%S)"
REPO_URL="${CONSOLEPI_HUB_REPO_URL:-https://github.com/LoveSkylark/ConsolePi-Hub}"
REPO_REF="${CONSOLEPI_HUB_REPO_REF:-main}"
RAW_BASE="${REPO_URL/github.com/raw.githubusercontent.com}/${REPO_REF}"
NEW_KEY_REQUESTED="false"
GET_KEY_REQUESTED="false"
RENDER_CONFIG_ONLY="false"
STATUS_ONLY="false"
CONSOLEPI_PRESEED_DIR="${SCRIPT_DIR}/consolepi-stage"
CONSOLEPI_PRESEED_FILE="${CONSOLEPI_PRESEED_DIR}/install.conf"
CONSOLEPI_PASSWORD=""
PRESEED_REMOVED="false"
KEEP_PRESEED="false"
HUB_REMOTE_SSH_USER="${HUB_REMOTE_SSH_USER:-}"
HUB_REMOTE_SSH_PUBKEY="${HUB_REMOTE_SSH_PUBKEY:-}"

is_valid_ipv4() {
  local ip="$1"
  local octet

  [[ "${ip}" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || return 1
  IFS='.' read -r -a octets <<< "${ip}"
  for octet in "${octets[@]}"; do
    ((octet >= 0 && octet <= 255)) || return 1
  done
}

derive_hub_ip_from_subnet() {
  local subnet="$1"
  local base_ip
  local prefix
  local o1
  local o2
  local o3
  local o4

  base_ip="${subnet%/*}"
  prefix="${subnet#*/}"

  if [[ "${prefix}" != "24" ]]; then
    echo "WG_SUBNET must be a /24 network: ${subnet}" >&2
    return 1
  fi

  is_valid_ipv4 "${base_ip}" || {
    echo "Invalid subnet base IP: ${base_ip}" >&2
    return 1
  }

  IFS='.' read -r o1 o2 o3 o4 <<< "${base_ip}"
  printf '%s.%s.%s.1' "${o1}" "${o2}" "${o3}"
}

derive_spoke_ip_from_subnet() {
  local subnet="$1"
  local spoke_index="$2"
  local base_ip
  local prefix
  local o1
  local o2
  local o3
  local o4
  local host_octet

  [[ "${spoke_index}" =~ ^[0-9]+$ ]] || {
    echo "WG_SPOKE must be a numeric slot index." >&2
    return 1
  }

  base_ip="${subnet%/*}"
  prefix="${subnet#*/}"

  if [[ "${prefix}" != "24" ]]; then
    echo "WG_SUBNET must be a /24 network: ${subnet}" >&2
    return 1
  fi

  is_valid_ipv4 "${base_ip}" || {
    echo "Invalid subnet base IP: ${base_ip}" >&2
    return 1
  }

  IFS='.' read -r o1 o2 o3 o4 <<< "${base_ip}"
  host_octet=$((10 + spoke_index))
  if ((host_octet < 11 || host_octet > 254)); then
    echo "Derived spoke host octet out of range for WG_SPOKE=${spoke_index}: ${host_octet}" >&2
    return 1
  fi

  printf '%s.%s.%s.%s' "${o1}" "${o2}" "${o3}" "${host_octet}"
}

derive_hub_port_from_profile() {
  local profile="$1"

  case "${profile}" in
    trusted)
      printf '51821'
      ;;
    untrusted)
      printf '51820'
      ;;
    *)
      echo "HUB_PROFILE must be 'trusted' or 'untrusted'" >&2
      return 1
      ;;
  esac
}

bool_is_true() {
  case "${1:-}" in
    true|TRUE|True|yes|YES|Yes|y|Y|1)
      return 0
      ;;
    false|FALSE|False|no|NO|No|n|N|0|"")
      return 1
      ;;
    *)
      echo "Invalid boolean value: ${1}" >&2
      return 2
      ;;
  esac
}

is_placeholder_value() {
  local value="$1"
  local placeholder="$2"

  [[ -z "${value}" || "${value}" == "${placeholder}" ]]
}

load_env_file() {
  if [[ ! -f "${ENV_FILE}" ]]; then
    echo "Missing ${ENV_FILE}. Copy .env.example to .env first." >&2
    return 1
  fi

  # shellcheck disable=SC1090
  source "${ENV_FILE}"
}

load_env_file_if_present() {
  if [[ -f "${ENV_FILE}" ]]; then
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
  fi
}

normalize_country() {
  local country="$1"

  [[ "${country}" =~ ^[A-Za-z]{2}$ ]] || {
    echo "COUNTRY must be a two-letter code such as US or GB." >&2
    return 1
  }

  printf '%s' "${country^^}"
}

extract_country_from_locale_value() {
  local locale_value="$1"

  [[ "${locale_value}" =~ ^[A-Za-z]+_([A-Za-z]{2})(\.|@|$) ]] || return 1
  printf '%s' "${BASH_REMATCH[1]^^}"
}

derive_default_country() {
  local locale_value
  local derived_country

  for locale_value in "${LC_ALL:-}" "${LANG:-}"; do
    if [[ -n "${locale_value}" ]] && derived_country="$(extract_country_from_locale_value "${locale_value}" 2>/dev/null)"; then
      printf '%s' "${derived_country}"
      return 0
    fi
  done

  if [[ -r /etc/default/locale ]]; then
    locale_value="$(awk -F= '/^(LANG|LC_ALL)=/ { gsub(/"/, "", $2); print $2; exit }' /etc/default/locale)"
    if [[ -n "${locale_value}" ]] && derived_country="$(extract_country_from_locale_value "${locale_value}" 2>/dev/null)"; then
      printf '%s' "${derived_country}"
      return 0
    fi
  fi

  printf 'US'
}

resolve_country_code() {
  local configured_country="${COUNTRY:-}"

  if [[ -n "${configured_country}" ]]; then
    normalize_country "${configured_country}"
    return 0
  fi

  derive_default_country
}

persist_env_file() {
  if [[ -f "${ENV_FILE}" ]]; then
    cp "${ENV_FILE}" "${ENV_FILE}.bak.${TIMESTAMP}"
  fi

  cat > "${ENV_FILE}" <<EOF
# Generated by deploy-spoke.sh on ${TIMESTAMP}
HUB_PROFILE=${HUB_PROFILE}
HUB_ENDPOINT=${HUB_ENDPOINT}
WG_SUBNET=${WG_SUBNET}
WG_SPOKE=${WG_SPOKE}
HUB_PUBLIC_KEY=${HUB_PUBLIC_KEY}
EOF

  printf 'HUB_REMOTE_SSH_USER=%q\n' "${HUB_REMOTE_SSH_USER}" >> "${ENV_FILE}"
  printf 'HUB_REMOTE_SSH_PUBKEY=%q\n' "${HUB_REMOTE_SSH_PUBKEY}" >> "${ENV_FILE}"
}

is_valid_ssh_public_key() {
  local key="$1"

  [[ "${key}" =~ ^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp(256|384|521))[[:space:]]+[A-Za-z0-9+/=]+([[:space:]].*)?$ ]]
}

resolve_default_remote_ssh_user() {
  if [[ -n "${SUDO_USER:-}" && "${SUDO_USER}" != "root" ]]; then
    printf '%s' "${SUDO_USER}"
    return 0
  fi

  if [[ -n "${USER:-}" && "${USER}" != "root" ]]; then
    printf '%s' "${USER}"
    return 0
  fi

  printf '%s' "consolepi"
}

ensure_hub_remote_ssh_access() {
  local target_user="$1"
  local target_key="$2"
  local target_home
  local target_auth_keys

  if ! id "${target_user}" >/dev/null 2>&1; then
    ${SUDO} useradd -m -s /bin/bash "${target_user}"
  fi

  target_home="$(${SUDO} getent passwd "${target_user}" | awk -F: '{print $6}')"
  [[ -n "${target_home}" ]] || target_home="/home/${target_user}"
  target_auth_keys="${target_home}/.ssh/authorized_keys"

  ${SUDO} install -d -m 700 -o "${target_user}" -g "${target_user}" "${target_home}/.ssh"
  ${SUDO} touch "${target_auth_keys}"
  ${SUDO} chown "${target_user}:${target_user}" "${target_auth_keys}"
  ${SUDO} chmod 600 "${target_auth_keys}"

  if ! ${SUDO} grep -Fqx "${target_key}" "${target_auth_keys}"; then
    printf '%s\n' "${target_key}" | ${SUDO} tee -a "${target_auth_keys}" >/dev/null
  fi
}

ensure_wg_command() {
  if command -v wg >/dev/null 2>&1; then
    return 0
  fi

  echo "wireguard-tools is required for key generation and --get-key." >&2
  return 1
}

generate_spoke_private_key() {
  ensure_wg_command || return 1
  wg genkey
}

derive_public_key_from_private_key() {
  local private_key="$1"

  ensure_wg_command || return 1
  printf '%s' "${private_key}" | wg pubkey
}

resolve_private_key_from_state() {
  local private_key="${SPOKE_PRIVATE_KEY:-}"

  if ! is_placeholder_value "${private_key}" "CHANGE_ME_SPOKE_PRIVATE_KEY"; then
    printf '%s' "${private_key}"
    return 0
  fi

  if [[ -f "${SCRIPT_DIR}/rendered/spoke.privatekey" ]]; then
    awk 'NF { print; exit }' "${SCRIPT_DIR}/rendered/spoke.privatekey"
    return 0
  fi

  if [[ -f "/etc/wireguard/wg0.privatekey" ]]; then
    awk 'NF { print; exit }' "/etc/wireguard/wg0.privatekey"
    return 0
  fi

  echo "No existing spoke private key found." >&2
  return 1
}

print_current_spoke_public_key() {
  local private_key
  local public_key

  load_env_file_if_present
  private_key="$(resolve_private_key_from_state)"
  public_key="$(derive_public_key_from_private_key "${private_key}")"
  echo "Current spoke public key: ${public_key}"
}

print_deployment_summary() {
  local hub_port
  local hub_tunnel_ip
  local spoke_tunnel_ip

  hub_port="$(derive_hub_port_from_profile "${HUB_PROFILE}")"
  hub_tunnel_ip="$(derive_hub_ip_from_subnet "${WG_SUBNET}")"
  spoke_tunnel_ip="$(derive_spoke_ip_from_subnet "${WG_SUBNET}" "${WG_SPOKE}")"

  echo "Deployment summary:"
  echo "Profile: ${HUB_PROFILE}"
  echo "Spoke slot: ${WG_SPOKE}"
  echo "Spoke tunnel address: ${spoke_tunnel_ip}/32"
  echo "Hub endpoint: ${HUB_ENDPOINT}:${hub_port}"
  echo "Hub tunnel address: ${hub_tunnel_ip}/32"
  echo "Persistent keepalive: ${PERSISTENT_KEEPALIVE}"
  echo "WireGuard config: /etc/wireguard/wg0.conf"
  echo "Spoke public key: ${SPOKE_PUBLIC_KEY}"
  echo "Spoke private key file: ${SPOKE_PRIVATE_KEY_FILE}"
  echo "Spoke public key file: ${SPOKE_PUBLIC_KEY_FILE}"
  echo "Remote SSH user for HUB access: ${HUB_REMOTE_SSH_USER}"

  if [[ "${PRESEED_REMOVED}" == "true" ]]; then
    echo "ConsolePi preseed file: removed after successful install"
  elif [[ "${INSTALL_CONSOLEPI}" == "true" ]]; then
    echo "ConsolePi preseed file: ${CONSOLEPI_PRESEED_FILE}"
    if [[ "${KEEP_PRESEED}" == "true" ]]; then
      echo "ConsolePi preseed retention: enabled by --keep-preseed"
    fi
  fi

  echo "Deployed public key file: /etc/wireguard/wg0.publickey"
  echo "Rendered summary: ${SCRIPT_DIR}/rendered/summary.txt"
  echo "ConsolePi API check: curl -s http://127.0.0.1:5000/api/v1.0/details | head"
  echo "ConsolePi mode: API-only (mDNS disabled)"
  echo
  echo "Next check: ${SUDO} wg show"
  print_runtime_status
}

print_runtime_status() {
  local wg_output

  echo
  echo "Runtime status:"

  if wg_output="$(wg show wg0 2>&1)"; then
    echo "  tunnel status: up (wg0 active)"
    echo "  wg show wg0:"
    while IFS= read -r line; do
      echo "    ${line}"
    done <<< "${wg_output}"
  else
    echo "  tunnel status: down (wg0 not active)"
    echo "  wg show wg0 error: ${wg_output}"
  fi

  if command -v systemctl >/dev/null 2>&1; then
    if systemctl is-active --quiet consolepi-api; then
      if command -v curl >/dev/null 2>&1 && curl -fsS --max-time 3 http://127.0.0.1:5000/api/v1.0/details >/dev/null 2>&1; then
        echo "  API status:    up (consolepi-api active and reachable)"
      elif command -v wget >/dev/null 2>&1 && wget -q -T 3 -O - http://127.0.0.1:5000/api/v1.0/details >/dev/null 2>&1; then
        echo "  API status:    up (consolepi-api active and reachable)"
      else
        echo "  API status:    down (service active but endpoint unreachable)"
      fi
    else
      echo "  API status:    down (consolepi-api service inactive)"
    fi
  else
    echo "  API status:    unknown (systemctl not available)"
  fi
}

