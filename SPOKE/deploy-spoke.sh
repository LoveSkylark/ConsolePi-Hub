  cat <<EOF
Usage: ./deploy-spoke.sh [options]

Options:
  --new-key       Force generation of a new spoke private key
  --get-key       Print the current spoke public key and exit
  --render-config Render spoke config from .env only (no install/apply)
  --status        Print live tunnel/API status and exit
  --keep-preseed  Keep ConsolePi preseed file after install
  --help          Show this help
EOF
}

for arg in "$@"; do
  case "$arg" in
    --new-key)
      NEW_KEY_REQUESTED="true"
      ;;
    --get-key)
      GET_KEY_REQUESTED="true"
      ;;
    --render-config)
      RENDER_CONFIG_ONLY="true"
      ;;
    --status)
      STATUS_ONLY="true"
      ;;
    --keep-preseed)
      KEEP_PRESEED="true"
      ;;
    --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: ${arg}" >&2
      usage >&2
      exit 1
      ;;
  esac
done

SUDO=""

download_repo_file() {
  local repo_path="$1"
  local target_path="$2"
  local url="${RAW_BASE}/${repo_path}"

  mkdir -p "$(dirname "${target_path}")"
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL "${url}" -o "${target_path}"
  elif command -v wget >/dev/null 2>&1; then
    wget -q "${url}" -O "${target_path}"
  else
    echo "Need curl or wget to pull missing files from ${REPO_URL}." >&2
    return 1
  fi
}

ensure_repo_asset() {
  local local_path="$1"
  local repo_path="$2"

  if [[ ! -f "${local_path}" ]]; then
    echo "Missing ${local_path}; pulling ${repo_path} from ${REPO_URL}@${REPO_REF}"
    download_repo_file "${repo_path}" "${local_path}"
  fi
}

render_config_from_env() {
  load_env_file || return 1

  local wg_profile
  local wg_subnet
  local wg_spoke
  local hub_port
  local hub_tunnel_ip
  local spoke_tunnel_ip
  local spoke_profile_label
  local spoke_private_key

  wg_profile="${HUB_PROFILE:-}"
  wg_subnet="${WG_SUBNET:-}"
  wg_spoke="${WG_SPOKE:-}"
  spoke_private_key="${SPOKE_PRIVATE_KEY:-}"

  : "${wg_profile:?HUB_PROFILE must be set}"
  : "${wg_subnet:?WG_SUBNET must be set}"
  : "${wg_spoke:?WG_SPOKE must be set}"
  : "${HUB_ENDPOINT:?HUB_ENDPOINT must be set}"
  : "${HUB_PUBLIC_KEY:?HUB_PUBLIC_KEY must be set}"
  PERSISTENT_KEEPALIVE="${PERSISTENT_KEEPALIVE:-25}"

  if is_placeholder_value "${spoke_private_key}" "CHANGE_ME_SPOKE_PRIVATE_KEY"; then
    spoke_private_key="$(resolve_private_key_from_state 2>/dev/null || true)"
  fi

  if [[ -z "${spoke_private_key}" ]]; then
    echo "No spoke private key available. Run full deploy to generate it, or use --new-key." >&2
    return 1
  fi

  if is_placeholder_value "${HUB_PUBLIC_KEY}" "CHANGE_ME_HUB_PUBLIC_KEY"; then
    echo "HUB_PUBLIC_KEY must be set to a real HUB public key." >&2
    return 1
  fi

  case "${wg_profile}" in
    trusted|untrusted)
      ;;
    *)
      echo "HUB_PROFILE must be 'trusted' or 'untrusted'" >&2
      return 1
      ;;
  esac

  hub_port="$(derive_hub_port_from_profile "${wg_profile}")"
  hub_tunnel_ip="$(derive_hub_ip_from_subnet "${wg_subnet}")"
  spoke_tunnel_ip="$(derive_spoke_ip_from_subnet "${wg_subnet}" "${wg_spoke}")"
  spoke_profile_label="$(printf '%s' "${wg_profile}" | tr '[:lower:]' '[:upper:]')"

  mkdir -p "${SCRIPT_DIR}/profiles" "${SCRIPT_DIR}/rendered"

  cat > "${SCRIPT_DIR}/profiles/wg0.conf.example" <<EOF
# ${spoke_profile_label} spoke template

[Interface]
Address = ${spoke_tunnel_ip}/32
PrivateKey = ${spoke_private_key}

[Peer]
PublicKey = ${HUB_PUBLIC_KEY}
Endpoint = ${HUB_ENDPOINT}:${hub_port}
AllowedIPs = ${hub_tunnel_ip}/32
PersistentKeepalive = ${PERSISTENT_KEEPALIVE}
EOF

  cp "${SCRIPT_DIR}/profiles/wg0.conf.example" "${SCRIPT_DIR}/rendered/wg0.conf"

  cat > "${SCRIPT_DIR}/rendered/summary.txt" <<EOF
  Rendered spoke profile: ${wg_profile}
  WG subnet: ${wg_subnet}
  Spoke slot: ${wg_spoke}
  Spoke address: ${spoke_tunnel_ip}/32
  Hub endpoint: ${HUB_ENDPOINT}:${hub_port}
  AllowedIPs: ${hub_tunnel_ip}/32
Output config: ${SCRIPT_DIR}/rendered/wg0.conf
EOF

    echo "Rendered ${wg_profile} spoke config at ${SCRIPT_DIR}/rendered/wg0.conf"
}

prompt_required() {
  local label="$1"
  local default_value="${2:-}"
  local reply

  while true; do
    if [[ -n "${default_value}" ]]; then
      read -r -p "${label} [${default_value}]: " reply
      reply="${reply:-${default_value}}"
    else
      read -r -p "${label}: " reply
    fi

    if [[ -n "${reply}" ]]; then
      printf '%s\n' "${reply}"
      return 0
    fi

    echo "A value is required."
  done
}

validate_port() {
  local port="$1"

  [[ "${port}" =~ ^[0-9]+$ ]] || return 1
  ((port >= 1 && port <= 65535))
}

prompt_port() {
  local label="$1"
  local default_value="$2"
  local reply

  while true; do
    reply="$(prompt_required "${label}" "${default_value}")"
    if validate_port "${reply}"; then
      printf '%s' "${reply}"
      return 0
    fi
    echo "Enter a valid port number."
  done
}

install_consolepi() {
  local installer="/tmp/ConsolePi-install-${TIMESTAMP}.sh"
  local system_timezone
  local system_hostname
  local country_code
  local locale_code

  system_timezone="$(timedatectl show -p Timezone --value 2>/dev/null || true)"
  system_timezone="${system_timezone:-UTC}"
  system_hostname="$(hostname -s 2>/dev/null || hostname 2>/dev/null || echo consolepi)"
  country_code="$(resolve_country_code)"
  locale_code="${country_code,,}"

  mkdir -p "${CONSOLEPI_PRESEED_DIR}"
  cat > "${CONSOLEPI_PRESEED_FILE}" <<EOF
hostname=${system_hostname}
tz=${system_timezone}
wlan_country=${country_code}
locale=${locale_code}
auto_launch=true
no_users=true
no_ipv6=true
do_blue=false
doapt=true
dopip=true
EOF
printf 'consolepi_pass=%q\n' "${CONSOLEPI_PASSWORD}" >> "${CONSOLEPI_PRESEED_FILE}"

  if command -v wget >/dev/null 2>&1; then
    wget -q https://raw.githubusercontent.com/Pack3tL0ss/ConsolePi/master/installer/install.sh -O "${installer}"
  else
    ${SUDO} apt-get update
    ${SUDO} apt-get install -y curl
    curl -fsSL https://raw.githubusercontent.com/Pack3tL0ss/ConsolePi/master/installer/install.sh -o "${installer}"
  fi

  ${SUDO} bash "${installer}" -C "${CONSOLEPI_PRESEED_FILE}" --silent -p "${CONSOLEPI_PASSWORD}"
  rm -f "${installer}"
}

systemd_unit_exists() {
  local unit_name="$1"
  systemctl list-unit-files --type=service --no-legend 2>/dev/null | awk '{print $1}' | grep -qx "${unit_name}"
}

configure_consolepi_api_only_mode() {
  if ! command -v systemctl >/dev/null 2>&1; then
    echo "Skipping ConsolePi service management: systemctl not available."
    return 0
  fi

  local api_unit="consolepi-api.service"
  local mdns_units=("consolepi-mdnsreg.service" "consolepi-mdnsbrowse.service")
  local unit

  # API must be reachable by the HUB to populate remote adapters.
  if systemd_unit_exists "${api_unit}"; then
    ${SUDO} systemctl enable --now consolepi-api >/dev/null 2>&1 || true
    echo "ConsolePi API service enabled."
  else
    echo "ConsolePi API service not found; skipping API enable."
  fi

  # API-only mode: disable mDNS advertise/browse services.
  for unit in "${mdns_units[@]}"; do
    if systemd_unit_exists "${unit}"; then
      ${SUDO} systemctl disable --now "${unit%.service}" >/dev/null 2>&1 || true
    fi
  done
  echo "ConsolePi mDNS services disabled (if present)."
}

harden_consolepi_account() {
  local nologin_shell=""

  if ! id consolepi >/dev/null 2>&1; then
    return 0
  fi

  if command -v passwd >/dev/null 2>&1; then
    ${SUDO} passwd -l consolepi >/dev/null 2>&1 || true
  fi

  nologin_shell="$(command -v nologin 2>/dev/null || true)"
  if [[ -n "${nologin_shell}" ]]; then
    ${SUDO} usermod -s "${nologin_shell}" consolepi >/dev/null 2>&1 || true
  fi

  echo "ConsolePi account hardened: password locked${nologin_shell:+, shell set to nologin}."
}

echo "ConnectPi spoke installer"
echo

ensure_repo_asset "${SCRIPT_DIR}/.env.example" "SPOKE/.env.example"

if [[ "${GET_KEY_REQUESTED}" == "true" ]]; then
  print_current_spoke_public_key
  exit 0
fi

if [[ "${RENDER_CONFIG_ONLY}" == "true" ]]; then
  render_config_from_env
  exit 0
fi

if [[ "${STATUS_ONLY}" == "true" ]]; then
  print_runtime_status
  exit 0
fi

if [[ ${EUID} -ne 0 ]]; then
  if command -v sudo >/dev/null 2>&1; then
    SUDO="sudo"
  else
    echo "Run as root or install sudo." >&2
    exit 1
  fi
fi

load_env_file_if_present

if [[ -z "${HUB_PROFILE:-}" ]]; then
  while true; do
    HUB_PROFILE="$(prompt_required "HUB profile (trusted/untrusted)" "untrusted")"
    case "${HUB_PROFILE}" in
      trusted|untrusted)
        break
        ;;
      *)
        echo "HUB_PROFILE must be trusted or untrusted."
        ;;
    esac
  done
fi

if [[ -z "${WG_SUBNET:-}" ]]; then
  if [[ "${HUB_PROFILE}" == "trusted" ]]; then
    WG_SUBNET="$(prompt_required "WireGuard subnet for this profile" "10.99.99.0/24")"
  else
    WG_SUBNET="$(prompt_required "WireGuard subnet for this profile" "10.99.98.0/24")"
  fi
fi

if [[ -z "${WG_SPOKE:-}" ]]; then
  WG_SPOKE="$(prompt_port "Spoke slot index" "1")"
fi

if [[ -z "${HUB_ENDPOINT:-}" ]]; then
  HUB_ENDPOINT="$(prompt_required "Hub endpoint hostname or public IP" "change-me.example.com")"
fi

if is_placeholder_value "${HUB_PUBLIC_KEY:-}" "CHANGE_ME_HUB_PUBLIC_KEY"; then
  HUB_PUBLIC_KEY="$(prompt_required "Hub public key")"
fi

PERSISTENT_KEEPALIVE="${PERSISTENT_KEEPALIVE:-25}"

INSTALL_CONSOLEPI="${INSTALL_CONSOLEPI:-true}"

if bool_is_true "${INSTALL_CONSOLEPI}"; then
  INSTALL_CONSOLEPI="true"
else
  INSTALL_CONSOLEPI="false"
fi

if is_placeholder_value "${HUB_PUBLIC_KEY}" "CHANGE_ME_HUB_PUBLIC_KEY"; then
  echo "HUB_PUBLIC_KEY must be set to a real HUB public key in ${ENV_FILE}." >&2
  exit 1
fi

if [[ -z "${HUB_REMOTE_SSH_USER}" ]]; then
  HUB_REMOTE_SSH_USER="$(prompt_required "Remote SSH user that HUB should use" "$(resolve_default_remote_ssh_user)")"
fi

while true; do
  if [[ -z "${HUB_REMOTE_SSH_PUBKEY}" ]]; then
    HUB_REMOTE_SSH_PUBKEY="$(prompt_required "HUB remote SSH public key (from HUB consolepi/ssh/hub_spoke_ed25519.pub)")"
  fi

  if is_valid_ssh_public_key "${HUB_REMOTE_SSH_PUBKEY}"; then
    break
  fi

  echo "Invalid SSH public key format. Paste a full key line such as ssh-ed25519 AAAA..."
  HUB_REMOTE_SSH_PUBKEY=""
done

${SUDO} apt-get update
${SUDO} apt-get install -y wireguard

if [[ "${NEW_KEY_REQUESTED}" == "true" ]] || is_placeholder_value "${SPOKE_PRIVATE_KEY:-}" "CHANGE_ME_SPOKE_PRIVATE_KEY"; then
  SPOKE_PRIVATE_KEY="$(generate_spoke_private_key)"
  echo "Generated spoke private key."
fi

SPOKE_PUBLIC_KEY="$(derive_public_key_from_private_key "${SPOKE_PRIVATE_KEY}")"

if [[ "${INSTALL_CONSOLEPI}" == "true" ]]; then
  CONSOLEPI_PASSWORD="$(od -An -N16 -tx1 /dev/urandom | tr -d ' \n')"
fi

mkdir -p "${SCRIPT_DIR}/rendered"
SPOKE_PRIVATE_KEY_FILE="${SCRIPT_DIR}/rendered/spoke.privatekey"
SPOKE_PUBLIC_KEY_FILE="${SCRIPT_DIR}/rendered/spoke.publickey"
printf '%s\n' "${SPOKE_PRIVATE_KEY}" > "${SPOKE_PRIVATE_KEY_FILE}"
printf '%s\n' "${SPOKE_PUBLIC_KEY}" > "${SPOKE_PUBLIC_KEY_FILE}"
chmod 600 "${SPOKE_PRIVATE_KEY_FILE}" "${SPOKE_PUBLIC_KEY_FILE}"

if [[ "${NEW_KEY_REQUESTED}" == "true" ]]; then
  echo "Rotated spoke keypair via --new-key."
  echo "Spoke public key: ${SPOKE_PUBLIC_KEY}"
  echo "Store this on the HUB for the matching peer slot."
fi

persist_env_file

render_config_from_env

${SUDO} mkdir -p /etc/wireguard
if [[ -f /etc/wireguard/wg0.conf ]]; then
  ${SUDO} cp /etc/wireguard/wg0.conf "/etc/wireguard/wg0.conf.bak.${TIMESTAMP}"
fi
${SUDO} cp "${SCRIPT_DIR}/rendered/wg0.conf" /etc/wireguard/wg0.conf
${SUDO} cp "${SPOKE_PRIVATE_KEY_FILE}" /etc/wireguard/wg0.privatekey
${SUDO} cp "${SPOKE_PUBLIC_KEY_FILE}" /etc/wireguard/wg0.publickey
${SUDO} chmod 600 /etc/wireguard/wg0.conf
${SUDO} chmod 600 /etc/wireguard/wg0.privatekey /etc/wireguard/wg0.publickey

${SUDO} systemctl enable wg-quick@wg0
if ${SUDO} systemctl is-active --quiet wg-quick@wg0; then
  ${SUDO} systemctl restart wg-quick@wg0
else
  ${SUDO} systemctl start wg-quick@wg0
fi

if [[ "${INSTALL_CONSOLEPI}" == "true" ]]; then
  install_consolepi
  # Preseed contains a password; remove it after a successful install unless requested otherwise.
  if [[ "${KEEP_PRESEED}" != "true" ]] && [[ -f "${CONSOLEPI_PRESEED_FILE}" ]]; then
    rm -f "${CONSOLEPI_PRESEED_FILE}"
    PRESEED_REMOVED="true"
  fi
fi

configure_consolepi_api_only_mode
harden_consolepi_account
ensure_hub_remote_ssh_access "${HUB_REMOTE_SSH_USER}" "${HUB_REMOTE_SSH_PUBKEY}"

echo
echo "Install complete."
print_deployment_summary